def role_template(role: str) -> dict:
    for name, tpl in ROLE_TEMPLATES.items():
        if name.lower() == (role or "").strip().lower():
            return tpl
    lowered = (role or "").lower()
    for name, tpl in ROLE_TEMPLATES.items():
        if any(tok in lowered for tok in name.lower().split() if tok not in {"developer", "engineer"}):
            return tpl
    return ROLE_TEMPLATES["Software Engineer"] if "engineer" in lowered or "developer" in lowered else GENERIC_ROLE


